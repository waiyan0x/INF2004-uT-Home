/** @file occwire.c
 * @brief Bounded ESPHome plaintext framing and one occupancy entity. */
#include "occwire.h"
#include <string.h>

static const uint8_t g_entity[] = {
    0x0aU, 14U,   'r', 'o', 'o',   'm', '_', 'o', 'c', 'c',   'u', 'p',
    'a',   'n',   'c', 'y', 0x15U, 1U,  0U,  0U,  0U,  0x1aU, 14U, 'R',
    'o',   'o',   'm', ' ', 'o',   'c', 'c', 'u', 'p', 'a',   'n', 'c',
    'y',   0x2aU, 9U,  'o', 'c',   'c', 'u', 'p', 'a', 'n',   'c', 'y'};

static void frame (occwire_t *     p_wire,
                   uint8_t         kind,
                   const uint8_t * p_bytes,
                   uint8_t         length)
{
    p_wire->transmit[0] = 0U;
    p_wire->transmit[1] = length;
    p_wire->transmit[2] = kind;
    if (0U < length)
    {
        memcpy(&p_wire->transmit[3], p_bytes, length);
    }
    p_wire->queued = (uint8_t)(3U + length);
    p_wire->sent   = 0U;
}

/* node is the boot MAC identity generated by c3net, not a client string. */
int occwire_step (occwire_t * p_wire, const char * p_node, uint8_t state)
{
    uint8_t body[64] = {0};
    if ((NULL == p_wire) || (NULL == p_node) || (19U != strlen(p_node)) ||
        (0 != strncmp(p_node, "uthome-", 7U)) || (2U < state) ||
        (0U != p_wire->queued) || (sizeof(p_wire->receive) < p_wire->used))
    {
        return -1;
    }
    if (2U <= p_wire->used)
    {
        const uint8_t length = p_wire->receive[1];
        if ((0U != p_wire->receive[0]) || (125U < length))
        {
            return -1;
        }
        if ((3U + length) <= p_wire->used)
        {
            const uint8_t kind = p_wire->receive[2];
            if (((!p_wire->b_hello) && (1U != kind)) || (128U <= kind))
            {
                return -1;
            }
            switch (kind)
            {
            case 1U:
                if (p_wire->b_hello)
                {
                    return -1;
                }
                body[0] = 8U;
                body[1] = 1U;
                body[2] = 16U;
                body[3] = 9U;
                body[4] = 34U;
                body[5] = 19U;
                memcpy(&body[6], p_node, 19U);
                frame(p_wire, 2U, body, 25U);
                p_wire->b_hello = true;
            break;
            case 3U:
                frame(p_wire, 4U, NULL, 0U);
            break;
            case 5U:
                frame(p_wire, 6U, NULL, 0U);
                p_wire->b_closing = true;
            break;
            case 7U:
                frame(p_wire, 8U, NULL, 0U);
            break;
            case 9U:
                body[0] = 18U;
                body[1] = 19U;
                memcpy(&body[2], p_node, 19U);
                body[21] = 26U;
                body[22] = 17U;
                for (size_t idx = 0U; idx < 6U; ++idx)
                {
                    size_t pos = 23U + idx * 3U;
                    memcpy(&body[pos], &p_node[7U + idx * 2U], 2U);
                    if (5U > idx)
                    {
                        body[pos + 2U] = ':';
                    }
                }
                frame(p_wire, 10U, body, 40U);
            break;
            case 11U:
                frame(p_wire, 12U, g_entity, (uint8_t)sizeof(g_entity));
                p_wire->transmit[p_wire->queued++] = 0U;
                p_wire->transmit[p_wire->queued++] = 0U;
                p_wire->transmit[p_wire->queued++] = 19U;
            break;
            case 20U:
                p_wire->b_subscribed = true;
                p_wire->last         = 3U;
            break;
            default: /* Unknown optional messages have no side effects. */
            break;
            }
            p_wire->used = (uint8_t)(p_wire->used - 3U - length);
            memmove(
                p_wire->receive, &p_wire->receive[3U + length], p_wire->used);
        }
    }
    if ((0U == p_wire->queued) && (p_wire->b_subscribed) &&
        (state != p_wire->last))
    {
        body[0] = 13U;
        body[1] = 1U;
        body[5] = 16U;
        body[6] = (uint8_t)(2U == state);
        body[7] = 24U;
        body[8] = (uint8_t)(0U == state);
        frame(p_wire, 21U, body, 9U);
        p_wire->last = state;
    }
    return 0;
}

