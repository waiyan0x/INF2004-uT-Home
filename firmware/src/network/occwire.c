/** @file occwire.c
 * @brief Bounded ESPHome plaintext framing for radar occupancy and freshness.
 */
#include "occwire.h"
#include <string.h>

static const uint8_t g_entity[] = {
    0x0aU, 14U,   'r', 'o', 'o',   'm', '_', 'o', 'c', 'c',   'u', 'p',
    'a',   'n',   'c', 'y', 0x15U, 1U,  0U,  0U,  0U,  0x1aU, 14U, 'R',
    'o',   'o',   'm', ' ', 'o',   'c', 'c', 'u', 'p', 'a',   'n', 'c',
    'y',   0x2aU, 9U,  'o', 'c',   'c', 'u', 'p', 'a', 'n',   'c', 'y'};

/* Binary sensor key 2, diagnostic category. String terminator is not sent. */
static const uint8_t g_fresh[]  = "\x0a\x10"
                                  "radar_data_fresh"
                                  "\x15\x02\x00\x00\x00"
                                  "\x1a\x10"
                                  "Radar data fresh"
                                  "\x48\x02";
static const uint8_t g_result[] = "\x0a\x12"
                                  "transaction_result"
                                  "\x15\x03\x00\x00\x00"
                                  "\x1a\x12"
                                  "Transaction result";

/* Two entity descriptions and list-done, each with a three-byte frame header.
 */
enum
{
    OCCWIRE_LIST_FITS = 1 / ((9U + sizeof(g_entity) + sizeof(g_fresh) - 1U) <=
                             sizeof(((occwire_t *)0)->transmit))
};

static void frame (occwire_t *     p_wire,
                   uint8_t         kind,
                   const uint8_t * p_bytes,
                   uint8_t         length)
{
    uint8_t * p_next = &p_wire->transmit[p_wire->queued];
    p_next[0]        = 0U;
    p_next[1]        = length;
    p_next[2]        = kind;
    if (0U < length)
    {
        memcpy(&p_next[3], p_bytes, length);
    }
    p_wire->queued = (uint8_t)(p_wire->queued + 3U + length);
    p_wire->sent   = 0U;
}

/* node is the boot MAC identity generated by c3net, not a client string. */
int occwire_step (occwire_t * p_wire, const char * p_node, uint8_t state)
{
    return occwire_transaction(p_wire, p_node, state, NULL, 0U);
}

/** @brief Encode copied result state; this endpoint never performs bus I/O. */
int occwire_transaction (occwire_t *          p_wire,
                         const char *         p_node,
                         uint8_t              state,
                         const txjob_view_t * p_view,
                         uint64_t             now_ms)
{
    uint8_t body[125] = {0};
    if ((NULL == p_wire) || (NULL == p_node) || (19U != strlen(p_node)) ||
        (0 != strncmp(p_node, "uthome-", 7U)) || (2U < state) ||
        (0U != p_wire->queued) || (sizeof(p_wire->receive) < p_wire->used))
    {
        return -1;
    }
    if (2U <= p_wire->used)
    {
        const uint8_t length = p_wire->receive[1];
        if ((0U != p_wire->receive[0]) || (125U < length))
        {
            return -1;
        }
        if ((3U + length) <= p_wire->used)
        {
            const uint8_t kind = p_wire->receive[2];
            if (((!p_wire->b_hello) && (1U != kind)) || (128U <= kind))
            {
                return -1;
            }
            switch (kind)
            {
            case 1U:
                if (p_wire->b_hello)
                {
                    return -1;
                }
                body[0] = 8U;
                body[1] = 1U;
                body[2] = 16U;
                body[3] = 9U;
                body[4] = 34U;
                body[5] = 19U;
                memcpy(&body[6], p_node, 19U);
                frame(p_wire, 2U, body, 25U);
                p_wire->b_hello = true;
            break;
            case 3U:
                frame(p_wire, 4U, NULL, 0U);
            break;
            case 5U:
                frame(p_wire, 6U, NULL, 0U);
                p_wire->b_closing = true;
            break;
            case 7U:
                frame(p_wire, 8U, NULL, 0U);
            break;
            case 9U:
                body[0] = 18U;
                body[1] = 19U;
                memcpy(&body[2], p_node, 19U);
                body[21] = 26U;
                body[22] = 17U;
                for (size_t idx = 0U; idx < 6U; ++idx)
                {
                    size_t pos = 23U + idx * 3U;
                    memcpy(&body[pos], &p_node[7U + idx * 2U], 2U);
                    if (5U > idx)
                    {
                        body[pos + 2U] = ':';
                    }
                }
                frame(p_wire, 10U, body, 40U);
            break;
            case 11U:
                frame(p_wire, 12U, g_entity, (uint8_t)sizeof(g_entity));
                frame(p_wire, 12U, g_fresh, (uint8_t)(sizeof(g_fresh) - 1U));
                p_wire->listing = 1U;
            break;
            case 20U:
                p_wire->b_subscribed = true;
                p_wire->last         = 3U;
                p_wire->b_job_sent   = false;
            break;
            default: /* Unknown optional messages have no side effects. */
            break;
            }
            p_wire->used = (uint8_t)(p_wire->used - 3U - length);
            memmove(
                p_wire->receive, &p_wire->receive[3U + length], p_wire->used);
            if (20U == kind)
            {
                /* Next owner tick captures the actual initial radar snapshot.
                 */
                return 0;
            }
        }
    }
    if ((0U == p_wire->queued) && (0U != p_wire->listing))
    {
        if (1U == p_wire->listing)
        {
            frame(p_wire, 18U, g_result, (uint8_t)(sizeof(g_result) - 1U));
            p_wire->listing = 2U;
        }
        else
        {
            frame(p_wire, 19U, NULL, 0U);
            p_wire->listing = 0U;
        }
        return 0;
    }
    if ((0U == p_wire->queued) && (p_wire->b_subscribed) &&
        (state != p_wire->last))
    {
        body[0] = 13U;
        body[1] = 1U;
        body[5] = 16U;
        body[6] = (uint8_t)(2U == state);
        body[7] = 24U;
        body[8] = (uint8_t)(0U == state);
        frame(p_wire, 21U, body, 9U);
        if ((3U == p_wire->last) || ((0U == state) != (0U == p_wire->last)))
        {
            body[1] = 2U;
            body[6] = (uint8_t)(0U != state);
            body[8] = 0U;
            frame(p_wire, 21U, body, 9U);
        }
        p_wire->last = state;
    }
    if ((0U == p_wire->queued) && (p_wire->b_subscribed))
    {
        char       text[120] = {0};
        const bool b_available =
            (NULL != p_view) &&
            (0 == txjob_text(p_view, now_ms, text, sizeof(text)));
        const uint32_t sequence = (NULL == p_view) ? 0U : p_view->sequence;
        if ((!p_wire->b_job_sent) || (sequence != p_wire->last_job) ||
            (b_available != p_wire->b_job_available))
        {
            body[0]             = 13U;
            body[1]             = 3U;
            const size_t length = b_available ? strlen(text) : 0U;
            body[5]             = 18U;
            body[6]             = (uint8_t)length;
            memcpy(&body[7], text, length);
            body[7U + length] = 24U;
            body[8U + length] = (uint8_t)(!b_available);
            frame(p_wire, 27U, body, (uint8_t)(9U + length));
            p_wire->last_job        = sequence;
            p_wire->b_job_sent      = true;
            p_wire->b_job_available = b_available;
        }
    }
    return 0;
}

