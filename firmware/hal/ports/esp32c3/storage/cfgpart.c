/** @brief Reject missing, out-of-range or noncanonical table chunks. */
bool cfgpart_check (const uint8_t * p_data, size_t offset, size_t size)
{
    if ((NULL == p_data) || (0U == size) ||
        (offset >= UTHOME_PART_TABLE_BYTES) ||
        (size > (UTHOME_PART_TABLE_BYTES - offset)))
    {
        return false;
    }
    for (size_t index = 0U; index < size; ++index)
    {
        const size_t  position = offset + index;
        const uint8_t expected =
            (position < sizeof(g_prefix)) ? g_prefix[position] : 0xFFU;
        if (expected != p_data[index])
        {
            return false;
        }
    }
    return true;
}

/** @brief Use subtraction bounds before calculating an end address. */
bool cfgpart_writable (size_t address, size_t size)
{
    if (address < UTHOME_PART_CONFIG_OFFSET)
    {
        return false;
    }
    const size_t offset = address - UTHOME_PART_CONFIG_OFFSET;
    return (offset <= UTHOME_PART_CONFIG_BYTES) &&
           (size <= (UTHOME_PART_CONFIG_BYTES - offset));
}

